#!/bin/bash
# Generate the code for the app <-> gateway messages (proto/vacuum.proto) for both ends, and the
# sample messages the app's tests read to prove both ends agree.
#   tools/gen_proto.sh           write everything
#   tools/gen_proto.sh --check   only check that what is on disk is up to date; exit 1 if not
#
# Python: protoc from pip grpcio-tools. Its generated code must not be newer than the protobuf
#         runtime the gateway imports (pip protobuf 6.33 on this PC; Ubuntu's 3.12 is too old).
# App:    pbjs and pbts from protobufjs-cli in app/node_modules (npm install first).
# Never edit the generated files by hand.
set -e
R="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
PY_OUT="$R/ros2_ws/src/motebot_robot/vacuum_gateway/vacuum_gateway"
TS_OUT="$R/app/src/proto"
SAMPLES="$R/proto/samples"

generate() {  # into the directory given: python/, ts/, samples/
  local out=$1
  mkdir -p "$out/python" "$out/ts" "$out/samples"
  python3 -m grpc_tools.protoc -I "$R/proto" --python_out="$out/python" --pyi_out="$out/python" "$R/proto/vacuum.proto"
  local banner="// Generated by tools/gen_proto.sh from proto/vacuum.proto. Do not edit."
  (cd "$R/app" && npx pbjs -t static-module -w commonjs --no-delimited --no-service --no-typeurl \
     -o "$out/ts/vacuum.js" "$R/proto/vacuum.proto" \
   && npx pbts -o "$out/ts/vacuum.d.ts" "$out/ts/vacuum.js")
  for f in "$out/ts/vacuum.js" "$out/ts/vacuum.d.ts"; do
    { echo "$banner"; cat "$f"; } > "$f.tmp" && mv "$f.tmp" "$f"
  done
  # The samples are written by the gateway's own code, using the Python code just generated.
  python3 - "$out" "$R" <<'EOF'
import os, shutil, sys
out, root = sys.argv[1], sys.argv[2]
pkg = os.path.join(out, "python_pkg", "vacuum_gateway")
shutil.copytree(os.path.join(root, "ros2_ws/src/motebot_robot/vacuum_gateway/vacuum_gateway"), pkg,
                ignore=shutil.ignore_patterns("vacuum_pb2.py*", "__pycache__"))
for f in ("vacuum_pb2.py", "vacuum_pb2.pyi"):
    shutil.copy(os.path.join(out, "python", f), pkg)
sys.path.insert(0, os.path.dirname(pkg))
from vacuum_gateway import samples
samples.write(os.path.join(out, "samples"))
EOF
}

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
generate "$TMP"

if [ "$1" = "--check" ]; then
  stale=0
  for pair in "python/vacuum_pb2.py:$PY_OUT/vacuum_pb2.py" "python/vacuum_pb2.pyi:$PY_OUT/vacuum_pb2.pyi" \
              "ts/vacuum.js:$TS_OUT/vacuum.js" "ts/vacuum.d.ts:$TS_OUT/vacuum.d.ts"; do
    cmp -s "$TMP/${pair%%:*}" "${pair#*:}" || { echo "out of date: ${pair#*:}"; stale=1; }
  done
  diff -rq "$TMP/samples" "$SAMPLES" >/dev/null 2>&1 || { echo "out of date: $SAMPLES"; stale=1; }
  [ $stale -eq 0 ] && echo "generated code and samples are up to date" || echo "run tools/gen_proto.sh"
  exit $stale
fi

mkdir -p "$PY_OUT" "$TS_OUT" "$SAMPLES"
cp "$TMP/python/vacuum_pb2.py" "$TMP/python/vacuum_pb2.pyi" "$PY_OUT/"
cp "$TMP/ts/vacuum.js" "$TMP/ts/vacuum.d.ts" "$TS_OUT/"
rm -f "$SAMPLES"/*.bin && cp "$TMP/samples/"*.bin "$SAMPLES/"
echo "wrote $PY_OUT/vacuum_pb2.py(i), $TS_OUT/vacuum.js, vacuum.d.ts, and $(ls "$SAMPLES" | wc -l) samples in $SAMPLES"
